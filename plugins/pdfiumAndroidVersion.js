const fs = require('fs');
const path = require('path');
const { withAppBuildGradle, withDangerousMod, withProjectBuildGradle } = require('expo/config-plugins');

const START = '// @generated by TillCalc: Android PDF renderer stability';
const END = '// @end generated TillCalc Android PDF renderer stability';
const JAVA_START = '        // @generated by TillCalc: instance-level PDFium close guard';
const JAVA_END = '        // @end generated TillCalc instance-level PDFium close guard';
const PDFIUM_VERSION = '1.0.34';
const VIEWER_AAR = 'AndroidPdfViewer-4.0.1-tillnote.aar';
const VIEWER_DEPENDENCY = "    implementation 'com.github.zacharee:AndroidPdfViewer:4.0.1'";
const VIEWER_FILES = `files(rootProject.file('../android-libs/${VIEWER_AAR}'))`;
// A library module cannot package a direct local .aar (AGP fails :react-native-pdf:bundleReleaseAar,
// which a root-level `gradlew assembleRelease` runs), so react-native-pdf only compiles against the
// patched viewer and the app module ships it.
const LEGACY_LOCAL_VIEWER_DEPENDENCY = `    implementation ${VIEWER_FILES}`;
const LOCAL_VIEWER_DEPENDENCY = `    compileOnly ${VIEWER_FILES}`;
const APP_VIEWER_DEPENDENCY = `    implementation ${VIEWER_FILES} // @generated by TillCalc: patched Android PDF viewer`;
const VIEWER_ANDROIDX_DEPENDENCY = "    implementation 'androidx.core:core:1.12.0'";

const buildBlock = () => `${START}
allprojects {
    configurations.configureEach {
        resolutionStrategy.force 'io.legere:pdfiumandroid:${PDFIUM_VERSION}'
    }
}
${END}`;

const patchPdfViewSource = source => {
  if (source.includes(JAVA_START)) return source;

  const javaImportAnchor = 'import java.io.IOException;';
  const pdfiumImportAnchor = 'import io.legere.pdfiumandroid.DefaultLogger;';
  const constructorAnchor = '        ConfigKt.setPdfiumConfig(new Config(new DefaultLogger(), AlreadyClosedBehavior.IGNORE));';
  for (const anchor of [javaImportAnchor, pdfiumImportAnchor, constructorAnchor]) {
    if (!source.includes(anchor)) {
      throw new Error(`[TillCalc] Cannot apply Android PDF close guard; react-native-pdf source changed near: ${anchor}`);
    }
  }

  return source
    .replace(javaImportAnchor, `${javaImportAnchor}\nimport java.lang.reflect.Field;`)
    .replace(pdfiumImportAnchor, `${pdfiumImportAnchor}\nimport io.legere.pdfiumandroid.PdfiumCore;`)
    .replace(constructorAnchor, `${constructorAnchor}\n${JAVA_START}\n        try {\n            Field field = PDFView.class.getDeclaredField("pdfiumCore");\n            field.setAccessible(true);\n            field.set(this, new PdfiumCore(context, new Config(new DefaultLogger(), AlreadyClosedBehavior.IGNORE)));\n        } catch (ReflectiveOperationException exception) {\n            throw new IllegalStateException("Unable to configure safe PdfiumCore close behavior", exception);\n        }\n${JAVA_END}`);
};

const withPdfiumCloseGuard = config => withDangerousMod(config, ['android', cfg => {
  const viewerAarPath = path.join(cfg.modRequest.projectRoot, 'android-libs', VIEWER_AAR);
  if (!fs.existsSync(viewerAarPath)) {
    throw new Error(`[TillCalc] Patched Android PDF viewer was not found: android-libs/${VIEWER_AAR}`);
  }

  const pdfBuildGradlePath = path.join(
    cfg.modRequest.projectRoot,
    'node_modules',
    'react-native-pdf',
    'android',
    'build.gradle',
  );
  if (!fs.existsSync(pdfBuildGradlePath)) {
    throw new Error('[TillCalc] react-native-pdf Android Gradle file was not found.');
  }
  const pdfBuildGradle = fs.readFileSync(pdfBuildGradlePath, 'utf8');
  let patchedBuildGradle = pdfBuildGradle.replace(LEGACY_LOCAL_VIEWER_DEPENDENCY, LOCAL_VIEWER_DEPENDENCY);
  if (!patchedBuildGradle.includes(LOCAL_VIEWER_DEPENDENCY)) {
    if (!patchedBuildGradle.includes(VIEWER_DEPENDENCY)) {
      throw new Error('[TillCalc] Cannot substitute patched Android PDF viewer; dependency contract changed.');
    }
    patchedBuildGradle = patchedBuildGradle.replace(VIEWER_DEPENDENCY, LOCAL_VIEWER_DEPENDENCY);
  }
  if (!patchedBuildGradle.includes(VIEWER_ANDROIDX_DEPENDENCY)) {
    patchedBuildGradle = patchedBuildGradle.replace(
      LOCAL_VIEWER_DEPENDENCY,
      `${LOCAL_VIEWER_DEPENDENCY}\n${VIEWER_ANDROIDX_DEPENDENCY}`,
    );
  }
  if (patchedBuildGradle !== pdfBuildGradle) fs.writeFileSync(pdfBuildGradlePath, patchedBuildGradle, 'utf8');

  const pdfViewPath = path.join(
    cfg.modRequest.projectRoot,
    'node_modules',
    'react-native-pdf',
    'android',
    'src',
    'main',
    'java',
    'org',
    'wonday',
    'pdf',
    'PdfView.java',
  );
  if (!fs.existsSync(pdfViewPath)) {
    throw new Error('[TillCalc] react-native-pdf Android source was not found; PDF close guard was not applied.');
  }
  const source = fs.readFileSync(pdfViewPath, 'utf8');
  const patched = patchPdfViewSource(source);
  if (patched !== source) fs.writeFileSync(pdfViewPath, patched, 'utf8');
  return cfg;
}]);

module.exports = function withPdfiumAndroidVersion(config) {
  const withPinnedPdfium = withProjectBuildGradle(config, cfg => {
    if (cfg.modResults.language !== 'groovy') {
      throw new Error('[TillCalc] Android PDF renderer stability requires a Groovy project build file.');
    }

    const blockPattern = new RegExp(`${START}[\\s\\S]*?${END}`, 'g');
    const withoutPreviousBlock = cfg.modResults.contents.replace(blockPattern, '').trimEnd();
    cfg.modResults.contents = `${withoutPreviousBlock}\n\n${buildBlock()}\n`;
    return cfg;
  });
  const withAppViewer = withAppBuildGradle(withPinnedPdfium, cfg => {
    if (cfg.modResults.language !== 'groovy') {
      throw new Error('[TillCalc] Android PDF viewer substitution requires a Groovy app build file.');
    }
    if (cfg.modResults.contents.includes(APP_VIEWER_DEPENDENCY)) return cfg;
    const anchor = /^dependencies\s*\{\s*$/m;
    if (!anchor.test(cfg.modResults.contents)) {
      throw new Error('[TillCalc] Cannot add patched Android PDF viewer; app dependencies block not found.');
    }
    cfg.modResults.contents = cfg.modResults.contents.replace(anchor, match => `${match}\n${APP_VIEWER_DEPENDENCY}`);
    return cfg;
  });
  return withPdfiumCloseGuard(withAppViewer);
};

module.exports.PDFIUM_VERSION = PDFIUM_VERSION;
module.exports.patchPdfViewSource = patchPdfViewSource;
